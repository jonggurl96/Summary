-- 기존 사용자 지우고 새로 생성
DROP ROLE IF EXISTS portfolio;

CREATE ROLE portfolio WITH LOGIN PASSWORD 'portfolio';

-- 기존 사용자 서비스 데이터베이스 지우고 새로 생성
DROP DATABASE IF EXISTS USERSERVICE;
CREATE DATABASE USERSERVICE WITH ENCODING 'UTF8' OWNER portfolio;
ALTER DATABASE USERSERVICE SET CLIENT_ENCODING TO 'UTF8';
ALTER DATABASE USERSERVICE SET TIMEZONE TO 'Asia/Seoul';